const fs = require("node:fs");
const path = require("node:path");

// Pages can retain deleted assets. Generate a guard from this build only.
const assetRoot = path.join("_site", "assets");
const assets = [];
function collect(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) collect(file);
    else assets.push("/" + path.relative("_site", file).split(path.sep).join("/"));
  }
}
collect(assetRoot);
for (const asset of [...assets]) {
  if (asset.endsWith("/index.html")) assets.push(asset.slice(0, -10), asset.slice(0, -11));
  else if (asset.endsWith(".html")) assets.push(asset.slice(0, -5));
}
const notFound = fs.readFileSync("_site/404.html", "utf8");
const handler = `// Generated by build-assets-guard.cjs. Do not edit.
const currentAssets = new Set(${JSON.stringify(assets.sort())});
const notFound = ${JSON.stringify(notFound)};
export async function onRequest({ request, env }) {
  let pathname;
  try { pathname = decodeURIComponent(new URL(request.url).pathname); }
  catch { return new Response("Bad request", { status: 400 }); }
  if (!currentAssets.has(pathname)) {
    return new Response(request.method === "HEAD" ? null : notFound, {
      status: 404,
      headers: {
        "Content-Type": "text/html; charset=utf-8",
        "Cache-Control": "no-store",
        "X-Assets-Guard": "missing"
      }
    });
  }
  const response = await env.ASSETS.fetch(request);
  const headers = new Headers(response.headers);
  headers.set("Cache-Control", "public, max-age=0, must-revalidate");
  headers.set("X-Assets-Guard", "current");
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers
  });
}
`;
fs.mkdirSync("functions/assets", { recursive: true });
fs.writeFileSync("functions/assets/[[path]].js", handler);
console.log("Generated asset guard for " + assets.length + " current files.");
